import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";
import prettier from "prettier";

const workspaceRoot = process.cwd();
const manifestSchemaPath = path.join(workspaceRoot, "rules/schema/manifest.schema.json");
const packageSchemaPath = path.join(workspaceRoot, "rules/schema/rule-package.schema.json");
const publicationRequestSchemaPath = path.join(
  workspaceRoot,
  "rules/schema/publication-request.schema.json",
);
const productionChannelConfigSchemaPath = path.join(
  workspaceRoot,
  "rules/schema/production-channel-config.schema.json",
);
const outputPath = path.join(workspaceRoot, "src/rules/contracts.generated.ts");
const validatorsOutputPath = path.join(workspaceRoot, "src/rules/schema-validators.generated.js");

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

function namespaceDefinitions(schema, prefix) {
  const namespaced = structuredClone(schema);
  const definitions = namespaced.$defs ?? {};
  const qualify = (name) => `${prefix}${name[0].toUpperCase()}${name.slice(1)}`;
  namespaced.$defs = Object.fromEntries(
    Object.entries(definitions).map(([name, value]) => [qualify(name), value]),
  );

  const rewriteReferences = (value) => {
    if (Array.isArray(value)) return value.map(rewriteReferences);
    if (value === null || typeof value !== "object") return value;

    return Object.fromEntries(
      Object.entries(value).map(([key, nested]) => {
        if (key === "$ref" && typeof nested === "string" && nested.startsWith("#/$defs/")) {
          return [key, `#/$defs/${qualify(nested.slice("#/$defs/".length))}`];
        }
        return [key, rewriteReferences(nested)];
      }),
    );
  };

  return rewriteReferences(namespaced);
}

async function generateContracts() {
  const [
    manifestSchema,
    rawPackageSchema,
    rawPublicationRequestSchema,
    rawProductionChannelConfigSchema,
  ] = await Promise.all([
    readJson(manifestSchemaPath),
    readJson(packageSchemaPath),
    readJson(publicationRequestSchemaPath),
    readJson(productionChannelConfigSchemaPath),
  ]);
  const packageSchema = namespaceDefinitions(rawPackageSchema, "Rule");
  const publicationRequestSchema = namespaceDefinitions(rawPublicationRequestSchema, "Publication");
  const productionChannelConfigSchema = namespaceDefinitions(
    rawProductionChannelConfigSchema,
    "ProductionConfig",
  );
  const options = {
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: true,
    style: { singleQuote: true, semi: true },
    unreachableDefinitions: false,
  };
  const [manifestTypes, packageTypes, publicationRequestTypes, productionChannelConfigTypes] =
    await Promise.all([
      compile(manifestSchema, "RuleManifest", options),
      compile(packageSchema, "RulePackage", options),
      compile(publicationRequestSchema, "RuleCatalogPublicationRequest", options),
      compile(productionChannelConfigSchema, "ProductionRuleCatalogChannelConfig", options),
    ]);
  const typesSource = [
    "// Generated from rules/schema/*.schema.json by npm run rules:generate.",
    "// Do not edit this file directly.",
    "",
    manifestTypes.trim(),
    "",
    packageTypes.trim(),
    "",
    publicationRequestTypes.trim(),
    "",
    productionChannelConfigTypes.trim(),
    "",
    "export type RuleManifest = PflegeShiftRuleManifest;",
    "export type RulePackage = PflegeShiftRulePackage;",
    "export type RuleCatalogPublicationRequest = PflegeShiftRuleCatalogPublicationRequest;",
    "export type ProductionRuleCatalogChannelConfig = PflegeShiftProductionRuleCatalogChannelConfig;",
    "",
  ].join("\n");

  const ajv = new Ajv2020({
    allErrors: true,
    code: { esm: true, source: true },
    strict: true,
    validateFormats: false,
  });
  ajv.addSchema(manifestSchema, "RuleManifest");
  ajv.addSchema(rawPackageSchema, "RulePackage");
  ajv.addSchema(rawPublicationRequestSchema, "RuleCatalogPublicationRequest");
  ajv.addSchema(rawProductionChannelConfigSchema, "ProductionRuleCatalogChannelConfig");
  const validatorsSource = [
    "/* eslint-disable */",
    "// Generated from rules/schema/*.schema.json by npm run rules:generate.",
    "// Do not edit this file directly.",
    standaloneCode(ajv, {
      validateManifestSchema: "RuleManifest",
      validateRulePackageSchema: "RulePackage",
      validateRuleCatalogPublicationRequestSchema: "RuleCatalogPublicationRequest",
      validateProductionRuleCatalogChannelConfigSchema: "ProductionRuleCatalogChannelConfig",
    }),
  ].join("\n");
  const prettierConfig = (await prettier.resolveConfig(outputPath)) ?? {};

  return {
    types: await prettier.format(typesSource, { ...prettierConfig, filepath: outputPath }),
    validators: await prettier.format(validatorsSource, {
      ...prettierConfig,
      filepath: validatorsOutputPath,
    }),
  };
}

const generated = await generateContracts();

if (process.argv.includes("--check")) {
  const readCurrent = async (filePath) => {
    try {
      return await fs.readFile(filePath, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      return "";
    }
  };
  const [currentTypes, currentValidators] = await Promise.all([
    readCurrent(outputPath),
    readCurrent(validatorsOutputPath),
  ]);

  if (currentTypes !== generated.types || currentValidators !== generated.validators) {
    console.error("Rule contracts are stale. Run: npm run rules:generate");
    process.exitCode = 1;
  } else {
    console.log("Generated rule contracts are current.");
  }
} else {
  await Promise.all([
    fs.writeFile(outputPath, generated.types, "utf8"),
    fs.writeFile(validatorsOutputPath, generated.validators, "utf8"),
  ]);
  console.log(
    `Generated ${path.relative(workspaceRoot, outputPath)} and ${path.relative(
      workspaceRoot,
      validatorsOutputPath,
    )}.`,
  );
}
